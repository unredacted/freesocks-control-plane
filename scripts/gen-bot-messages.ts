/**
 * Regenerate the Telegram gift shop's text catalog
 * (`convex/lib/telegram/botMessages.generated.ts`) from the `bot` group of
 * `messages/<locale>.json`. The bot runs in the Convex backend, which has no
 * Paraglide runtime, so its strings are copied out here. Keeping them in the
 * main catalogs means `bun run i18n:review` puts them in the human
 * translation packets like every other string. Run by `i18n:keys`.
 *
 * Bot strings are simple messages only (no plural variants): a variant would
 * need Paraglide's runtime to pick its form.
 */
import { readFileSync, writeFileSync } from 'node:fs';

export const BOT_LOCALES = ['en', 'fa', 'ar', 'ru', 'zh'] as const;
export const BOT_MESSAGES_PATH = 'convex/lib/telegram/botMessages.generated.ts';

function botGroup(raw: string, locale: string): Record<string, string> {
  const catalog = JSON.parse(raw) as Record<string, unknown>;
  const group = catalog.bot;
  if (group === undefined) return {};
  if (!group || typeof group !== 'object' || Array.isArray(group)) {
    throw new Error(`messages/${locale}.json: "bot" must be a group of messages`);
  }
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(group as Record<string, unknown>)) {
    if (typeof v !== 'string') {
      throw new Error(`messages/${locale}.json: bot.${k} must be a simple message (no variants)`);
    }
    out[k] = v;
  }
  return out;
}

/** The generated module's source, from the locale catalogs `read` returns. */
export function buildBotMessagesSource(
  read: (locale: string) => string = (l) => readFileSync(`messages/${l}.json`, 'utf8'),
): string {
  const en = botGroup(read('en'), 'en');
  const enKeys = Object.keys(en).sort();
  const lines: string[] = [
    '// AUTO-GENERATED by scripts/gen-bot-messages.ts from the `bot` group of',
    '// messages/<locale>.json. Do not edit; run `bun run i18n:keys`.',
    '',
    'export const BOT_MESSAGES_EN = {',
    ...enKeys.map((k) => `  ${k}: ${JSON.stringify(en[k])},`),
    '} as const;',
    '',
    'export type BotMessageKey = keyof typeof BOT_MESSAGES_EN;',
    `export type BotLocale = ${BOT_LOCALES.map((l) => `'${l}'`).join(' | ')};`,
    `export const BOT_LOCALES: readonly BotLocale[] = [${BOT_LOCALES.map((l) => `'${l}'`).join(', ')}];`,
    '',
    '/** Translations present so far; a missing key falls back to English. */',
    'export const BOT_MESSAGES: Record<BotLocale, Partial<Record<BotMessageKey, string>>> = {',
    '  en: BOT_MESSAGES_EN,',
  ];
  for (const locale of BOT_LOCALES) {
    if (locale === 'en') continue;
    const tr = botGroup(read(locale), locale);
    const keys = enKeys.filter((k) => typeof tr[k] === 'string' && tr[k] !== '');
    lines.push(`  ${locale}: {`, ...keys.map((k) => `    ${k}: ${JSON.stringify(tr[k])},`), '  },');
  }
  lines.push('};', '');
  return lines.join('\n');
}

if (import.meta.main) {
  writeFileSync(BOT_MESSAGES_PATH, buildBotMessagesSource());
  // eslint-disable-next-line no-console
  console.log(`wrote ${BOT_MESSAGES_PATH}`);
}
