/**
 * Telegram gift shop config (docs/billing.md § "Telegram gift shop"). Stored
 * in the `appSettings` `telegram.*` namespace (like `alerts.*`: NOT in
 * SETTINGS_DEFAULTS, so it gets typed validation here and never leaks through
 * the generic settings allowlist). Ships OFF: the bot answers "closed" until
 * an admin turns the shop on, and each payment method has its own switch.
 *
 * SECRETS follow the billing.secret.* pattern: `telegram.secret.*` rows,
 * write-only from the admin card (blank = unchanged), shown back only as
 * set/not-set, with the env vars as a fallback. The bot token is the
 * BotFather token (also part of every Bot API URL); the webhook secret is the
 * `secret_token` Telegram echoes in x-telegram-bot-api-secret-token on every
 * update, generated by Register webhook when none is set.
 */
import type { DatabaseReader } from '../_generated/server';
import { MAX_DURATION_MONTHS } from './billingConfig';

export interface StarsPrice {
  months: number;
  /** Whole Telegram Stars for ONE code of this duration. */
  stars: number;
}

export interface TelegramConfig {
  /** The shop. Off = the bot only says it is closed. */
  enabled: boolean;
  /** The bot's public @username, without the @ ('' = unset). */
  botUsername: string;
  /** Telegram Stars payments (still needs a Stars price for a duration). */
  starsEnabled: boolean;
  starsPrices: StarsPrice[];
  /** Full terms of sale the bot links ('' = the bot's own short terms only). */
  termsUrl: string;
  /**
   * The bot whose webhook Register pointed here (its numeric id, the
   * non-secret part of the token); '' after Remove or before any Register.
   * State, not a setting: only the webhook actions write it.
   */
  webhookBotId: string;
}

export const TELEGRAM_KEYS = {
  enabled: 'telegram.enabled',
  botUsername: 'telegram.botUsername',
  starsEnabled: 'telegram.stars.enabled',
  starsPrices: 'telegram.stars.prices',
  termsUrl: 'telegram.termsUrl',
  webhookBotId: 'telegram.webhook.botId',
} as const;

/** Write-only credentials (DB first, then env). */
export const TELEGRAM_SECRET_KEYS = {
  botToken: 'telegram.secret.botToken',
  webhookSecret: 'telegram.secret.webhookSecret',
} as const;

/** A BotFather token: `<bot id>:<secret>`. */
export const BOT_TOKEN_RE = /^\d{5,16}:[A-Za-z0-9_-]{30,64}$/;

/** The bot's numeric id: the part of its token before the colon (not secret). */
export function botIdOf(token: string): string {
  return BOT_TOKEN_RE.test(token) ? token.slice(0, token.indexOf(':')) : '';
}
/** What Telegram accepts as a webhook secret_token. */
export const WEBHOOK_SECRET_RE = /^[A-Za-z0-9_-]{1,256}$/;

export const TELEGRAM_DEFAULTS: TelegramConfig = {
  enabled: false,
  botUsername: '',
  starsEnabled: false,
  starsPrices: [],
  termsUrl: '',
  webhookBotId: '',
};

/** Upper bound on a Stars price per code (Telegram caps one invoice at 10,000 Stars x quantity anyway). */
export const MAX_STARS_PER_CODE = 100_000;

/** A Telegram bot username as BotFather allows it, with an optional leading @; else ''. */
export function sanitizeBotUsername(v: unknown): string {
  if (typeof v !== 'string') return '';
  const s = v.trim().replace(/^@/, '');
  return /^[A-Za-z0-9_]{5,32}$/.test(s) ? s : '';
}

/** An https terms link (no credentials), else ''. */
export function sanitizeTermsUrl(v: unknown): string {
  if (typeof v !== 'string') return '';
  const s = v.trim();
  if (!s || s.length > 500) return '';
  try {
    const u = new URL(s);
    return u.protocol === 'https:' && !u.username && !u.password ? u.toString() : '';
  } catch {
    return '';
  }
}

/**
 * Stars prices: whole months 1-MAX_DURATION_MONTHS (the billing catalog's cap) and whole Stars 1..MAX_STARS_PER_CODE,
 * one per duration (the first wins), sorted by months. Anything invalid is
 * dropped. Returns null when the input isn't an array at all.
 */
export function sanitizeStarsPrices(v: unknown): StarsPrice[] | null {
  if (!Array.isArray(v)) return null;
  const seen = new Set<number>();
  const out: StarsPrice[] = [];
  for (const row of v) {
    if (!row || typeof row !== 'object') continue;
    const { months, stars } = row as Record<string, unknown>;
    if (
      typeof months !== 'number' ||
      !Number.isInteger(months) ||
      months < 1 ||
      months > MAX_DURATION_MONTHS
    ) {
      continue;
    }
    if (
      typeof stars !== 'number' ||
      !Number.isInteger(stars) ||
      stars < 1 ||
      stars > MAX_STARS_PER_CODE
    ) {
      continue;
    }
    if (seen.has(months)) continue;
    seen.add(months);
    out.push({ months, stars });
  }
  return out.sort((a, b) => a.months - b.months);
}

async function readSetting(db: DatabaseReader, key: string): Promise<unknown> {
  const row = await db
    .query('appSettings')
    .withIndex('by_key', (q) => q.eq('key', key))
    .unique();
  if (!row) return undefined;
  try {
    return JSON.parse(row.value);
  } catch {
    return undefined;
  }
}

export interface TelegramSecrets {
  /** '' = unset. */
  botToken: string;
  /** '' = unset (the webhook route answers 503). */
  webhookSecret: string;
}

/** The bot's credentials: a saved row, else the env fallback. Internal use only. */
export async function resolveTelegramSecrets(db: DatabaseReader): Promise<TelegramSecrets> {
  const pick = (saved: unknown, envName: string, re: RegExp): string => {
    const s = typeof saved === 'string' ? saved.trim() : '';
    if (s && re.test(s)) return s;
    const e = (process.env[envName] ?? '').trim();
    return e && re.test(e) ? e : '';
  };
  const [token, secret] = await Promise.all([
    readSetting(db, TELEGRAM_SECRET_KEYS.botToken),
    readSetting(db, TELEGRAM_SECRET_KEYS.webhookSecret),
  ]);
  return {
    botToken: pick(token, 'TELEGRAM_BOT_TOKEN', BOT_TOKEN_RE),
    webhookSecret: pick(secret, 'TELEGRAM_WEBHOOK_SECRET', WEBHOOK_SECRET_RE),
  };
}

export async function resolveTelegramConfig(db: DatabaseReader): Promise<TelegramConfig> {
  const read = (key: string) => readSetting(db, key);
  const [enabled, botUsername, starsEnabled, starsPrices, termsUrl, webhookBotId] =
    await Promise.all([
      read(TELEGRAM_KEYS.enabled),
      read(TELEGRAM_KEYS.botUsername),
      read(TELEGRAM_KEYS.starsEnabled),
      read(TELEGRAM_KEYS.starsPrices),
      read(TELEGRAM_KEYS.termsUrl),
      read(TELEGRAM_KEYS.webhookBotId),
    ]);
  return {
    enabled: enabled === true,
    botUsername: sanitizeBotUsername(botUsername),
    starsEnabled: starsEnabled === true,
    starsPrices: sanitizeStarsPrices(starsPrices) ?? [],
    termsUrl: sanitizeTermsUrl(termsUrl),
    webhookBotId:
      typeof webhookBotId === 'string' && /^\d{5,16}$/.test(webhookBotId) ? webhookBotId : '',
  };
}

export interface TelegramConfigPatch {
  enabled?: boolean;
  botUsername?: string;
  starsEnabled?: boolean;
  starsPrices?: unknown;
  /** '' clears it. */
  termsUrl?: string;
  /** Write-only: undefined or blank leaves the saved token as it is. */
  botToken?: string;
}

/**
 * Validate an admin patch into appSettings writes. Throws a plain Error with
 * a reason on a bad field (the caller maps it to a validation error); an
 * empty bot username clears it.
 */
export function telegramConfigWrites(
  patch: TelegramConfigPatch,
): { key: string; value: unknown }[] {
  const writes: { key: string; value: unknown }[] = [];
  const bool = (name: keyof TelegramConfigPatch, key: string) => {
    const v = patch[name];
    if (v === undefined) return;
    if (typeof v !== 'boolean') throw new Error(`${name} must be true or false`);
    writes.push({ key, value: v });
  };
  bool('enabled', TELEGRAM_KEYS.enabled);
  bool('starsEnabled', TELEGRAM_KEYS.starsEnabled);
  if (patch.botUsername !== undefined) {
    const raw = typeof patch.botUsername === 'string' ? patch.botUsername.trim() : null;
    if (raw === null) throw new Error('botUsername must be text');
    const name = sanitizeBotUsername(raw);
    if (raw !== '' && !name) {
      throw new Error('botUsername must be 5 to 32 letters, digits or underscores');
    }
    writes.push({ key: TELEGRAM_KEYS.botUsername, value: name });
  }
  if (patch.starsPrices !== undefined) {
    const prices = sanitizeStarsPrices(patch.starsPrices);
    if (!prices || prices.length !== (patch.starsPrices as unknown[]).length) {
      throw new Error(
        `starsPrices must be a list of { months: 1-${MAX_DURATION_MONTHS}, stars: 1-${MAX_STARS_PER_CODE} }, one per duration`,
      );
    }
    writes.push({ key: TELEGRAM_KEYS.starsPrices, value: prices });
  }
  if (patch.termsUrl !== undefined) {
    if (typeof patch.termsUrl !== 'string') throw new Error('termsUrl must be text');
    const url = sanitizeTermsUrl(patch.termsUrl);
    if (patch.termsUrl.trim() !== '' && !url) throw new Error('termsUrl must be an https link');
    writes.push({ key: TELEGRAM_KEYS.termsUrl, value: url });
  }
  if (patch.botToken !== undefined) {
    if (typeof patch.botToken !== 'string') throw new Error('botToken must be text');
    const token = patch.botToken.trim();
    if (token !== '') {
      if (!BOT_TOKEN_RE.test(token)) {
        throw new Error(
          'botToken must be the token BotFather gave you (digits, a colon, then the secret)',
        );
      }
      writes.push({ key: TELEGRAM_SECRET_KEYS.botToken, value: token });
    }
  }
  return writes;
}
